package com.eignex.koblas.dense

/*
 * The double-precision names of this package under the aliases they had before the element type reached
 * them. [com.eignex.koblas.Precision] says why they carry it.
 */

/** Double-precision [F64VectorKernels], the vector-vector half an unqualified `VectorKernels` means. */
public typealias VectorKernels = F64VectorKernels

/** Double-precision [F64Blas], the matrix half an unqualified `Blas` means. */
public typealias Blas = F64Blas

/** Double-precision [F64Lapack], the factorization half an unqualified `Lapack` means. */
public typealias Lapack = F64Lapack

/** Double-precision [F64LinearAlgebra], the pair of halves an unqualified `LinearAlgebra` means. */
public typealias LinearAlgebra = F64LinearAlgebra

/** Double-precision [F64ReferenceBackend], the portable backend an unqualified `ReferenceBackend` means. */
public typealias ReferenceBackend = F64ReferenceBackend

/** Double-precision [F64HostBlasAdapter], the CBLAS adapter an unqualified `HostBlasAdapter` means. */
public typealias HostBlasAdapter = F64HostBlasAdapter

/** Double-precision [F64HostLapackAdapter], the LAPACKE adapter an unqualified `HostLapackAdapter` means. */
public typealias HostLapackAdapter = F64HostLapackAdapter

/** Double-precision [F64LuDecomposition], the LU factors an unqualified `LuDecomposition` means. */
public typealias LuDecomposition = F64LuDecomposition

/** Double-precision [F64CholeskyDecomposition], the Cholesky factor an unqualified `CholeskyDecomposition` means. */
public typealias CholeskyDecomposition = F64CholeskyDecomposition

/** Double-precision [F64QrDecomposition], the QR factors an unqualified `QrDecomposition` means. */
public typealias QrDecomposition = F64QrDecomposition

/** Double-precision [F64LdlDecomposition], the LDLt factors an unqualified `LdlDecomposition` means. */
public typealias LdlDecomposition = F64LdlDecomposition

/** Double-precision [F64PivotedQrDecomposition], the pivoted QR an unqualified `PivotedQrDecomposition` means. */
public typealias PivotedQrDecomposition = F64PivotedQrDecomposition
